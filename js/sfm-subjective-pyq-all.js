(function(){
  function init(){
    var t=document.getElementById("subTopic"),a=document.getElementById("subAttempt"),l=document.getElementById("subList"),c=document.getElementById("subCount");
    if(!t||!a||!l||!c)return;
    var topics=[];
    window.SFM_SUBJECTIVE_PYQ.forEach(function(x){if(topics.indexOf(x.t)<0)topics.push(x.t);});
    t.innerHTML="<option value=''>Select Chapter / Topic</option>"+topics.map(function(x){return "<option value='"+x.replace(/'/g,"&#39;")+"'>"+x+"</option>";}).join("");
    function render(){
      var topic=t.value,att=a.value;
      var rows=window.SFM_SUBJECTIVE_PYQ.filter(function(x){return x.t===topic&&(att==="all"||x.a===att);});
      c.textContent=topic?(rows.length+" subjective PYQ"+(rows.length===1?"":"s")+" found"):"Select a chapter/topic to view the PYQs.";
      l.innerHTML="";
      rows.forEach(function(x){
        var d=document.createElement("div");d.className="card";
        d.innerHTML="<div style='display:flex;justify-content:space-between;gap:10px;align-items:center;flex-wrap:wrap'><h2 style='margin:0'>Question "+x.q+" · "+x.a+"</h2><span style='font-size:.8rem;color:var(--muted)'>Original paper page "+x.p+"</span></div><div class='pyq-question'>"+x.html+"</div>";
        l.appendChild(d);
      });
    }
    t.onchange=render;a.onchange=render;render();
  }
  if(document.readyState==="loading")document.addEventListener("DOMContentLoaded",init);else init();
})();